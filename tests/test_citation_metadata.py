"""Regression coverage for consistent research-software citation metadata."""

from __future__ import annotations

import json
import shutil
from pathlib import Path

import pytest
import yaml
from scripts.verify_citation_metadata import verify_citation_metadata

from uplift_marketing import __version__

ROOT = Path(__file__).resolve().parents[1]
TAG = f"v{__version__}"
METADATA_PATHS = (
    ".zenodo.json",
    "CITATION.cff",
    "pyproject.toml",
    "src/uplift_marketing/__init__.py",
)


@pytest.fixture
def metadata_copy(tmp_path: Path) -> Path:
    """Copy only the metadata inputs, so rejected cases cannot alter the repo."""
    for relative_path in METADATA_PATHS:
        target = tmp_path / relative_path
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / relative_path, target)
    return tmp_path


def test_publication_metadata_matches_current_source() -> None:
    """A future version bump must update both citation metadata formats."""
    verify_citation_metadata(TAG, ROOT)


def test_release_tag_drift_is_rejected() -> None:
    """An arbitrary GitHub Release tag must not use this metadata unchanged."""
    with pytest.raises(ValueError, match="release tag does not match package version"):
        verify_citation_metadata("v99.0.0", ROOT)


def test_zenodo_version_drift_is_rejected(metadata_copy: Path) -> None:
    """Zenodo must archive the same version as the release and Python code."""
    path = metadata_copy / ".zenodo.json"
    metadata = json.loads(path.read_text(encoding="utf-8"))
    metadata["version"] = "v99.0.0"
    path.write_text(json.dumps(metadata), encoding="utf-8")
    with pytest.raises(ValueError, match="version does not match tag"):
        verify_citation_metadata(TAG, metadata_copy)


def test_cff_version_drift_is_rejected(metadata_copy: Path) -> None:
    """GitHub's generated citations must match the installed package version."""
    path = metadata_copy / "CITATION.cff"
    metadata = yaml.safe_load(path.read_text(encoding="utf-8"))
    metadata["version"] = "99.0.0"
    path.write_text(yaml.safe_dump(metadata), encoding="utf-8")
    with pytest.raises(ValueError, match="version does not match package"):
        verify_citation_metadata(TAG, metadata_copy)


